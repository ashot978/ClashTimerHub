 private I18n(){}
 static boolean english(Context context){return !"nl".equals(AppData.prefs(context).getString("language","en"));}
 static String code(Context context){return english(context)?"en":"nl";}
 static String flag(Context context){return english(context)?"🇬🇧":"🇳🇱";}
 static String label(Context context){return english(context)?"English":"Nederlands";}
 static void choose(Context context,String language){
  AppData.prefs(context).edit().putString("language","nl".equals(language)?"nl":"en").apply();
  TimerWidget.update(context);
 }
 static String tr(Context context,String value){
  if(value==null||!english(context))return value;
  String result=value;
  for(Map.Entry<String,String> item:EN.entrySet())result=result.replace(item.getKey(),item.getValue());
  return result;
 }
